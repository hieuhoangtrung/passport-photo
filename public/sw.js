// Offline cache. Pages: network first, so updates show at once. Files: cache first.
// ponytail: models and MediaPipe files are not hashed - change CACHE when you update them.
const CACHE = 'passport-photo-v1';

self.addEventListener('install', (e) => {
  self.skipWaiting();
  e.waitUntil(caches.open(CACHE).then((c) => c.add('/')));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/api/')) return;
  const save = (res) => {
    if (res.ok) {
      const copy = res.clone();
      caches.open(CACHE).then((c) => c.put(req, copy));
    }
    return res;
  };
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(save).catch(async () => (await caches.match(req)) ?? caches.match('/')));
  } else {
    e.respondWith(caches.match(req).then((hit) => hit ?? fetch(req).then(save)));
  }
});
